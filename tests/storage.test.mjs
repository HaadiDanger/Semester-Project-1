import { after, before, test } from "node:test"
import assert from "node:assert/strict"
import { createDatabase, asRole, rpc } from "./helpers/database.mjs"
import { createUser, readyAsset, profileReferences, publishProfile, saveProfile, token, validMetadata, worker } from "./helpers/records.mjs"

let db, admin, owner, other, refs
before(async () => {
  db = await createDatabase()
  admin = await createUser(db, { role: "admin" }); owner = await createUser(db); other = await createUser(db)
  refs = await profileReferences(db, admin)
})
after(async () => { await db?.close() })
const reserve = (id, purpose = "photo") => rpc(db, id, "reserve_asset", { p_purpose: purpose, p_request_id: token() })
const access = (asset, viewer) => worker(db, "worker_asset_access", { p_id: asset, p_viewer_id: viewer })

test("Storage insert policy accepts only an owned, unexpired reservation and provides no client reads or updates", async () => {
  const asset = await reserve(owner)
  const upload = (user, bucket, path) => asRole(db, "authenticated", user, "insert into storage.objects(bucket_id,name,owner_id) values($1,$2,$3)", [bucket, path, user])
  await assert.rejects(upload(other, asset.bucket, asset.path), /row-level security/)
  await assert.rejects(upload(owner, "profile-media", asset.path + ".webp"), /row-level security/)
  await assert.rejects(upload(owner, asset.bucket, `${owner}/${token()}`), /row-level security/)
  await upload(owner, asset.bucket, asset.path)
  const read = await asRole(db, "authenticated", owner, "select * from storage.objects where name=$1", [asset.path])
  assert.equal(read.rows.length, 0)
  assert.equal((await asRole(db, "authenticated", owner, "delete from storage.objects where name=$1 returning id", [asset.path])).rows.length, 0)
  assert.equal((await asRole(db, "authenticated", owner, "update storage.objects set metadata='{}' where name=$1 returning id", [asset.path])).rows.length, 0)
  const expired = await reserve(owner)
  await db.query("update private.assets set expires_at=now()-interval '1 minute' where id=$1", [expired.id])
  await assert.rejects(upload(owner, expired.bucket, expired.path), /row-level security/)
})

test("asset workers require service credentials, verify ownership, and reject missing validation metadata", async () => {
  const asset = await reserve(owner)
  await assert.rejects(rpc(db, owner, "worker_claim_asset", { p_id: asset.id, p_user_id: owner }), /permission denied/)
  await assert.rejects(worker(db, "worker_claim_asset", { p_id: asset.id, p_user_id: other }), /not available/)
  const claim = await worker(db, "worker_claim_asset", { p_id: asset.id, p_user_id: owner })
  await assert.rejects(worker(db, "worker_claim_asset", { p_id: asset.id, p_user_id: owner }), /already processing/)
  await assert.rejects(worker(db, "worker_complete_asset", { p_id: asset.id, p_user_id: owner, p_token: token(), p_metadata: validMetadata }), /claim expired or changed/)
  await assert.rejects(worker(db, "worker_complete_asset", { p_id: asset.id, p_user_id: owner, p_token: claim.token, p_metadata: {} }), /check constraint/)
  await assert.rejects(worker(db, "worker_complete_asset", { p_id: asset.id, p_user_id: owner, p_token: claim.token, p_metadata: { ...validMetadata, sha256: "z".repeat(64) } }), /check constraint/)
  await worker(db, "worker_complete_asset", { p_id: asset.id, p_user_id: owner, p_token: claim.token, p_metadata: validMetadata })
  assert.equal((await worker(db, "worker_claim_asset", { p_id: asset.id, p_user_id: owner })).state, "ready")
  assert.ok(await access(asset.id, owner))
  await assert.rejects(access(asset.id, other), /not available/)
})

test("photo audiences are checked on every gateway access, and private photo pointers cannot be selected directly", async () => {
  const photo = await readyAsset(db, owner)
  let saved = await saveProfile(db, owner, refs, { photo_asset_id: photo.id, photo_audience: "owner" })
  let p = await publishProfile(db, owner, admin, saved.write_version)
  assert.equal((await rpc(db, null, "get_profile", { p_id: owner })).photo_asset_id, null)
  await assert.rejects(asRole(db, "anon", null, "select photo_asset_id from public.profiles where id=$1", [owner]), /permission denied/)
  await assert.rejects(asRole(db, "authenticated", other, "select * from public.profiles where id=$1", [owner]), /permission denied/)
  await assert.rejects(access(photo.id, null), /not available/)
  assert.ok(await access(photo.id, admin), "genuine moderators may preview images")
  saved = await saveProfile(db, owner, refs, { photo_asset_id: photo.id, photo_audience: "public" }, p.write_version)
  p = await publishProfile(db, owner, admin, saved.write_version)
  assert.ok(await access(photo.id, null))
  await rpc(db, owner, "profile_action", { p_action: "unpublish", p_expected_version: p.write_version, p_request_id: token() })
  await assert.rejects(access(photo.id, null), /not available/)
  assert.ok(await access(photo.id, owner))
  await assert.rejects(saveProfile(db, other, refs, { photo_asset_id: photo.id }), /does not belong/)
})

test("evidence is administrator-only and referenced historical evidence cannot be deleted or swept", async () => {
  await assert.rejects(reserve(other, "price_evidence"), /administrator/i)
  const evidence = await readyAsset(db, admin, "price_evidence")
  await assert.rejects(access(evidence.id, null), /not available/)
  await assert.rejects(access(evidence.id, other), /not available/)
  assert.ok(await access(evidence.id, admin))
  const audit = (await db.query("select actor_user_id,action from private.admin_audit_log where target_key=$1 and action='asset.evidence_read'", [evidence.id])).rows
  assert.deepEqual(audit, [{ actor_user_id: admin, action: "asset.evidence_read" }], "only authorized evidence access is audited")
  // Minimal trusted history fixture: insertion exercises all base constraints.
  const category = token(), menu = token(), canteen = token(), offering = token(), price = token()
  await db.query("insert into public.food_categories(id,name,key) values($1,'test food','test food')", [category])
  await db.query("insert into public.menu_items(id,food_category_id,name,name_key) values($1,$2,'test item','test item')", [menu, category])
  await db.query("insert into public.canteens(id,name,key) values($1,'test canteen','test canteen')", [canteen])
  await db.query("insert into public.canteen_offerings(id,canteen_id,menu_item_id) values($1,$2,$3)", [offering, canteen, menu])
  await db.query("insert into private.price_records(id,offering_id,event_kind,amount,recorded_by,request_id) values($1,$2,'set',1,$3,$4)", [price, offering, admin, token()])
  await db.query("insert into private.price_verifications(price_record_id,decision,observed_at,actor_user_id,source_method,evidence_asset_id,reason,request_id) values($1,'verified',now(),$2,'displayed_menu',$3,'test',$4)", [price, admin, evidence.id, token()])
  await assert.rejects(rpc(db, admin, "delete_my_asset", { p_id: evidence.id, p_request_id: token() }), /Historical evidence is retained/)
  const jobs = await worker(db, "worker_claim_cleanup", { p_limit: 100 })
  const job = jobs.find(job => job.id === evidence.id)
  assert.ok(job)
  assert.equal(job.delete_final, false)
})

test("cleanup is leased, repeatable, backs off failures, and invalidates access before deleting final bytes", async () => {
  const unused = await readyAsset(db, other, "portfolio")
  await rpc(db, other, "delete_my_asset", { p_id: unused.id, p_request_id: token() })
  await assert.rejects(access(unused.id, other), /not available/)
  const jobs = await worker(db, "worker_claim_cleanup", { p_limit: 100 })
  const job = jobs.find(job => job.id === unused.id)
  assert.ok(job?.delete_final)
  assert.equal((await worker(db, "worker_claim_cleanup", { p_limit: 100 })).some(job => job.id === unused.id), false)
  await assert.rejects(worker(db, "worker_finish_cleanup", { p_id: job.id, p_token: token(), p_success: true }), /claim changed/)
  await worker(db, "worker_finish_cleanup", { p_id: job.id, p_token: job.token, p_success: false })
  assert.equal((await worker(db, "worker_claim_cleanup", { p_limit: 100 })).some(job => job.id === unused.id), false)
  await db.query("update private.assets set cleanup_expires_at=now()-interval '1 minute' where id=$1", [unused.id])
  const retry = (await worker(db, "worker_claim_cleanup", { p_limit: 100 })).find(job => job.id === unused.id)
  assert.notEqual(retry.token, job.token)
  await worker(db, "worker_finish_cleanup", { p_id: retry.id, p_token: retry.token, p_success: true })
  assert.equal((await db.query("select state from private.assets where id=$1", [unused.id])).rows[0].state, "deleted")
  assert.equal((await rpc(db, other, "get_my_assets")).some(asset => asset.id === unused.id), false)
})

test("suspension and role revocation stop existing processing claims from publishing images", async () => {
  const owner = await createUser(db)
  const asset = await reserve(owner)
  const claim = await worker(db, "worker_claim_asset", { p_id: asset.id, p_user_id: owner })
  await db.query("update private.account_controls set account_status='suspended' where user_id=$1", [owner])
  await assert.rejects(worker(db, "worker_complete_asset", { p_id: asset.id, p_user_id: owner, p_token: claim.token, p_metadata: validMetadata }), /permitted account/)
  const a = await createUser(db, { role: "admin" })
  const evidence = await reserve(a, "price_evidence")
  const evidenceClaim = await worker(db, "worker_claim_asset", { p_id: evidence.id, p_user_id: a })
  await db.query("delete from private.user_roles where user_id=$1", [a])
  await assert.rejects(worker(db, "worker_complete_asset", { p_id: evidence.id, p_user_id: a, p_token: evidenceClaim.token, p_metadata: validMetadata }), /Administrator/)
})

test("pending submissions, removal and deletion requests close every upload entry point, including existing reservations and claims", async () => {
  const id = await createUser(db)
  let p = await saveProfile(db, id, refs)
  const reserved = await reserve(id), processing = await reserve(id)
  const claim = await worker(db, "worker_claim_asset", { p_id: processing.id, p_user_id: id })
  p = await rpc(db, id, "profile_action", { p_action: "submit", p_expected_version: p.write_version, p_request_id: token() })
  const denied = async () => {
    await assert.rejects(reserve(id), /Withdraw|deletion request/)
    await assert.rejects(asRole(db, "authenticated", id, "insert into storage.objects(bucket_id,name,owner_id) values($1,$2,$3)", [reserved.bucket, reserved.path, id]), /row-level security/)
    await assert.rejects(worker(db, "worker_claim_asset", { p_id: reserved.id, p_user_id: id }), /no longer accept uploads/)
    await assert.rejects(worker(db, "worker_complete_asset", { p_id: processing.id, p_user_id: id, p_token: claim.token, p_metadata: validMetadata }), /no longer accept uploads/)
  }
  await denied()
  p = await rpc(db, id, "profile_action", { p_action: "unpublish", p_expected_version: p.write_version, p_request_id: token() })
  assert.ok((await reserve(id)).id, "withdrawal permits a new reservation")
  await rpc(db, admin, "admin_moderate_profile", { p_user_id: id, p_action: "remove", p_expected_version: p.write_version,
    p_data: { reason: "Test removal during an upload" }, p_request_id: token() })
  await denied()
  p = await rpc(db, id, "get_my_profile")
  await rpc(db, admin, "admin_moderate_profile", { p_user_id: id, p_action: "restore", p_expected_version: p.write_version,
    p_data: { reason: "Test restoration" }, p_request_id: token() })
  p = await rpc(db, id, "get_my_profile")
  await rpc(db, id, "profile_action", { p_action: "request_deletion", p_expected_version: p.write_version, p_request_id: token() })
  await denied()
})
